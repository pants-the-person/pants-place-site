import fs from 'node:fs';
import path from 'node:path';
import { loadWineApps, desktopAppIds, appLabel } from './apps.mjs';
import {
  publicWineRoot,
  generatedRoot,
  lockPath,
  categoryOf,
  defaultSizeByApp,
  featuredApps,
} from './config.mjs';

const mod = loadWineApps();
const ids = desktopAppIds(mod);
const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
const iconRoot = path.join(publicWineRoot, 'icons/apps');

function iconFor(id) {
  const png = path.join(iconRoot, `${id}.png`);
  if (fs.existsSync(png)) return `/wine/icons/apps/${id}.png`;
  return '/wine/icons/icon-192.png';
}

function sizeFor(id) {
  const files = lock.apps[id]?.paths || [];
  return files.reduce((sum, rel) => sum + (lock.files[rel]?.size || 0), 0);
}

const entries = ids.map((id) => {
  const app = mod.APPS[id] || {};
  const size = defaultSizeByApp[id] || { w: 840, h: 600 };
  return {
    id,
    title: appLabel(mod, id),
    icon: iconFor(id),
    category: categoryOf(id),
    sizeBytes: sizeFor(id),
    exe: app.exe || null,
    watApp: app.watApp || null,
    defaultWidth: size.w,
    defaultHeight: size.h,
    featured: featuredApps.includes(id),
    experimental: id === 'screensavers' || id === 'halflife_uplink',
    missing: lock.apps[id]?.missing || [],
  };
});

const banner = `// Generated by scripts/wine/gen-registry.mjs. Do not edit.\n`;
const typeSource = `${banner}
export type WineAppCategory = 'accessories' | 'games' | 'system';

export interface WineAppInfo {
  id: string;
  title: string;
  icon: string;
  category: WineAppCategory;
  sizeBytes: number;
  exe: string | null;
  watApp: string | null;
  defaultWidth: number;
  defaultHeight: number;
  featured: boolean;
  experimental: boolean;
  missing: string[];
}

export const wineApps: WineAppInfo[] = ${JSON.stringify(entries, null, 2)};

export const wineAppsById: Record<string, WineAppInfo> = Object.fromEntries(
  wineApps.map((app) => [app.id, app]),
);

export const wineAppsByCategory = {
  accessories: wineApps.filter((app) => app.category === 'accessories'),
  games: wineApps.filter((app) => app.category === 'games'),
  system: wineApps.filter((app) => app.category === 'system'),
};
`;

fs.mkdirSync(generatedRoot, { recursive: true });
fs.writeFileSync(path.join(generatedRoot, 'wine-apps.ts'), typeSource);

fs.mkdirSync(publicWineRoot, { recursive: true });
fs.writeFileSync(
  path.join(publicWineRoot, 'apps.manifest.json'),
  JSON.stringify({
    generatedAt: lock.generatedAt,
    excludedApps: lock.excludedApps,
    apps: Object.fromEntries(ids.map((id) => [
      id,
      {
        title: entries.find((entry) => entry.id === id)?.title,
        icon: iconFor(id),
        category: categoryOf(id),
        sizeBytes: sizeFor(id),
        files: lock.apps[id]?.paths || [],
        missing: lock.apps[id]?.missing || [],
      },
    ])),
  }, null, 2) + '\n',
);

console.log(`Wine registry: ${entries.length} apps (${featuredApps.length} featured)`);
